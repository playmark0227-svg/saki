/* フラグからエンディングを合成して返す */
function computeEnding(char, flags) {
  const e = ENDINGS[char];
  const f = e.flags;
  const ri = ROUTE_ORDER.indexOf(char);
  if (flags[f.reject]) {
    const r = e.reject;
    return { code: 97 + ri, total: 100, who: char, exp: r.exp, bg: r.bg, title: r.title, body: r.body.slice(), rank: "BAD" };
  }
  const b1 = flags[f.b1] ? 1 : 0;
  const b2 = flags[f.b2] ? 1 : 0;
  const b3 = flags[f.b3] ? 1 : 0;
  let b4 = (flags[f.b4] != null) ? Number(flags[f.b4]) : 0;
  if (!(b4 >= 0 && b4 <= 2)) b4 = 0;
  const combo = b1 * 4 + b2 * 2 + b3;             // 0..7
  const a = e.accept;
  const code = ri * 24 + b4 * 8 + combo + 1;       // 1..96
  const bondScore = b1 + b2 + b3 + b4;             // 演出用（0..5）
  const rank = bondScore >= 4 ? "TRUE" : (bondScore >= 2 ? "GOOD" : "SWEET");
  return {
    code, total: 100, who: char, exp: a.exp, bg: a.bg[b4],
    title: a.base[b4] + "　～ " + a.subs[combo] + " ～",
    body: [a.openA[b4], a.blkB1[b1], a.blkB2[b2], a.blkB3[b3], a.closing],
    rank,
  };
}

window.ROUTE_ORDER = ROUTE_ORDER;
window.ENDINGS = ENDINGS;
window.computeEnding = computeEnding;
